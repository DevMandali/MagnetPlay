package torrent

import (
	"context"
	"fmt"
	"log"
	"sync"
	"time"

	pb "server/proto"

	lt "github.com/anacrolix/torrent"
)

func InitializeTorrentClient() (*lt.Client, error) {
	clientConfig := lt.NewDefaultClientConfig()
	clientConfig.DataDir = "./downloads"
	client, err := lt.NewClient(clientConfig)
	if err != nil {
		return nil, fmt.Errorf("Failed to create libtorrent client: %v", err)
	}
	return client, nil
}

type TorrentService struct {
	client *lt.Client
	pb.UnimplementedTorrentServiceServer

	torrents map[string]*lt.Torrent
	mu       sync.Mutex
}

func NewTorrentService(client *lt.Client) *TorrentService {
	return &TorrentService{
		client:   client,
		torrents: make(map[string]*lt.Torrent),
	}
}

func (s *TorrentService) AddTorrent(ctx context.Context, request *pb.TorrentRequest) (*pb.TorrentResponse, error) {
	magnetURL := request.GetMagnetURL()

	torrent, ok := s.GetTorrent(magnetURL, "")
	if ok != nil {
		return &pb.TorrentResponse{
			Status: pb.TorrentStatus_NOT_FOUND,
		}, nil
	}
	// Get info hash to use as torrent ID
	infoHash := torrent.InfoHash().String()

	// Torrent is now added and metadata is available, we can extract the information we need to return to the client
	info := torrent.Info()

	// Get torrent name
	name := info.Name
	log.Printf("Torrent name: %s", name)

	// Get list of files in the torrent and their sizes
	torrentFiles := info.Files

	// If fiels are empty, it might be a single-file torrent
	if len(torrentFiles) == 0 {
		return &pb.TorrentResponse{
			TorrentId: infoHash,
			Name:      name,
			Status:    pb.TorrentStatus_SINGLE_FILE,
		}, nil
	}

	// If there are files, it's a multi-file torrent. We need to extract the file paths and sizes
	fileInfoList := []*pb.FileInfo{}
	for i, file := range torrentFiles {
		// Hash for each file can be generated by combining the torrent info hash with the file index, this way we can uniquely identify each file within the torrent
		id := fmt.Sprintf("%s:%d", infoHash, i)
		fileInfoList = append(fileInfoList, &pb.FileInfo{
			Id:   id,
			Name: file.DisplayPath(info),
			Size: file.Length,
		})
		log.Printf("File: %s, Size: %d bytes", file.Path, file.Length)
	}

	return &pb.TorrentResponse{
		TorrentId: infoHash,
		Name:      name,
		Files:     fileInfoList,
		Status:    pb.TorrentStatus_MULTI_FILE,
	}, nil
}

// GetTorrent checks if the torrent already exists in the map, if not it adds it and waits for metadata to be available
func (s *TorrentService) GetTorrent(magnetURL string, infoHash string) (*lt.Torrent, error) {
	s.mu.Lock()
	defer s.mu.Unlock()

	// Check if torrent already exists
	if infoHash != "" {
		torrent, exists := s.torrents[infoHash]
		if exists {
			return torrent, nil
		}
	}

	// If not, add it
	torrent, err := s.client.AddMagnet(magnetURL)
	if err != nil {
		return nil, fmt.Errorf("failed to add torrent: %v", err)
	}

	// Wait for metadata
	select {
	case <-torrent.GotInfo():
		// metadata received
	case <-time.After(60 * time.Second):
		return nil, fmt.Errorf("timeout waiting for torrent metadata")
	}

	// Cache it in the map
	s.torrents[torrent.InfoHash().String()] = torrent
	return torrent, nil
}
